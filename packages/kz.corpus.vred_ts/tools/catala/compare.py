# --------------------------------------------------------------------------
# Independent Python reference (for --property): fractions and its own calendar.
# --------------------------------------------------------------------------
class Reference:
    def __init__(self, calendar: dict):
        self.start = dt.date.fromisoformat(calendar["nachalo"])
        self.end = dt.date.fromisoformat(calendar["konets_isklyuchitelno"])
        self.holidays = {dt.date.fromisoformat(d) for d in calendar["nerabochie_dni"]}

    def working(self, day: dt.date) -> bool:
        return day.weekday() < 5 and day not in self.holidays

    def nth_working_after(self, day: dt.date, n: int):
        if not (self.start <= day < self.end):
            return None
        cur, left = day, n
        while left > 0:
            cur += dt.timedelta(days=1)
            if not (self.start <= cur < self.end):
                return None
            if self.working(cur):
                left -= 1
        return cur.isoformat()

    @staticmethod
    def gibel(i: dict) -> dict:
        costs, market = i.get("ozhidaemye_raskhody"), i.get("rynochnaya_stoimost")
        net = True if (costs is not None and market is not None
                       and Fraction(costs) > Fraction(market) * Fraction(4, 5)) else None
        unich = True if (i.get("tekhnicheski_nevozmozhno") or net) else None
        vyplata = None
        if unich and market is not None:
            per = i.get("ostatki_peredany")
            if per is True:
                vyplata = market
            elif per is False and i.get("stoimost_godnykh_ostatkov") is not None:
                vyplata = market - i["stoimost_godnykh_ostatkov"]
        return {"netselesoobrazno": net, "unichtozheno": unich, "vyplata": vyplata}

    @staticmethod
    def detal(i: dict) -> dict:
        km = i.get("srednegodovoy_probeg_km")
        tselaya = i.get("ranee_ne_povrezhdalas") and i.get("ne_podvergalas_remontu")
        bez = None
        if i.get("podlezhit_zamene") and tselaya and km is not None:
            if i.get("vladelets") == "FizicheskoeLitso" and i.get("ne_podlezhit_tekhosmotru") and km <= 15000:
                bez = True
            if i.get("vladelets") == "YuridicheskoeLitso" and i.get("na_garantiynom_obsluzhivanii") and km <= 20000:
                bez = True
        if bez:
            stoimost = i.get("stoimost_novoy")
        else:
            stoimost = i.get("stoimost_s_uchetom_iznosa")
        return {"bez_iznosa": bez, "stoimost": stoimost}

    @staticmethod
    def vybor(i: dict) -> dict:
        n = i.get("predlozheno")
        return {"obespechen": None if n is None else n >= 2}

    def sroki(self, i: dict) -> dict:
        out = {k: None for k in ("predel_otmetki", "predel_otveta", "predel_otcheta", "otchet_ne_v_srok", "pravo_na_vyplatu")}
        if i.get("uproshchennoe_oformlenie"):
            return out
        if i.get("otchet_poluchen"):
            out["predel_otmetki"] = self.nth_working_after(dt.date.fromisoformat(i["otchet_poluchen"]), 3)
        if i.get("otmetka_nesoglasiya_poluchena"):
            out["predel_otveta"] = self.nth_working_after(dt.date.fromisoformat(i["otmetka_nesoglasiya_poluchena"]), 3)
        if i.get("osmotr_osushchestvlen"):
            out["predel_otcheta"] = self.nth_working_after(dt.date.fromisoformat(i["osmotr_osushchestvlen"]), 5)
        due = out["predel_otcheta"]
        if due:
            late = i.get("otchet_poluchen") and i["otchet_poluchen"] > due
            never = (i.get("otchet_predostavlen") is False and i.get("den_rassmotreniya")
                     and i["den_rassmotreniya"] > due)
            if late or never:
                out["otchet_ne_v_srok"] = True
                out["pravo_na_vyplatu"] = True
        return out

    def compute(self, scope: str, inputs: dict) -> dict:
        return {"Gibel": self.gibel, "StoimostDetali": self.detal, "VyborOtsenshchikov": self.vybor,
                "SrokiPunkta3": self.sroki}[scope](inputs)


