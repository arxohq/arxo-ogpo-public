def random_case(rng: random.Random, scope: str) -> dict:
    def maybe(value, p=0.85):
        return value if rng.random() < p else None
    if scope == "Gibel":
        market = rng.choice([0, 1, rng.randint(1, 10_000_000), rng.randint(1, 10_000_000)])
        costs_choice = rng.random()
        costs = (market * 4 // 5 if costs_choice < 0.25 else market * 4 // 5 + 1 if costs_choice < 0.5
                 else rng.randint(0, 10_000_000))
        i = {"tekhnicheski_nevozmozhno": rng.random() < 0.3}
        if maybe(True) is not None:
            i["ozhidaemye_raskhody"] = costs
        if maybe(True) is not None:
            i["rynochnaya_stoimost"] = market
        per = rng.choice([True, False, None])
        if per is not None:
            i["ostatki_peredany"] = per
        if maybe(True, 0.7) is not None:
            i["stoimost_godnykh_ostatkov"] = rng.randint(0, 2_000_000)
        return i
    if scope == "StoimostDetali":
        i = {"podlezhit_zamene": rng.random() < 0.85, "ne_podlezhit_tekhosmotru": rng.random() < 0.6,
             "na_garantiynom_obsluzhivanii": rng.random() < 0.6, "ranee_ne_povrezhdalas": rng.random() < 0.85,
             "ne_podvergalas_remontu": rng.random() < 0.85}
        owner = rng.choice(["FizicheskoeLitso", "YuridicheskoeLitso", None])
        if owner:
            i["vladelets"] = owner
        km = rng.choice([15000, 15001, 20000, 20001, rng.randint(0, 40000), None])
        if km is not None:
            i["srednegodovoy_probeg_km"] = km
        if maybe(True) is not None:
            i["stoimost_novoy"] = rng.randint(1, 1_000_000)
        if maybe(True) is not None:
            i["stoimost_s_uchetom_iznosa"] = rng.randint(1, 1_000_000)
        return i
    if scope == "VyborOtsenshchikov":
        n = rng.choice([0, 1, 2, 3, rng.randint(0, 10), None])
        return {} if n is None else {"predlozheno": n}
    if scope == "SrokiPunkta3":
        def day():
            return (dt.date(2026, 1, 1) + dt.timedelta(days=rng.randint(-3, 370))).isoformat()
        i = {"uproshchennoe_oformlenie": rng.random() < 0.15}
        for key, p in (("otchet_poluchen", 0.6), ("otmetka_nesoglasiya_poluchena", 0.4), ("osmotr_osushchestvlen", 0.7)):
            if rng.random() < p:
                i[key] = day()
        pred = rng.choice([True, False, None])
        if pred is not None:
            i["otchet_predostavlen"] = pred
        if rng.random() < 0.6:
            i["den_rassmotreniya"] = day()
        return i
    raise SystemExit(scope)


def run_property(count: int, seed: int, python: str, with_lawc: bool) -> int:
    cases = load_cases()
    calendar = load_calendar(cases)
    ref = Reference(calendar)
    rng = random.Random(seed)
    scopes = ["Gibel", "StoimostDetali", "VyborOtsenshchikov", "SrokiPunkta3"]
    generated = []
    for n in range(count):
        scope = scopes[n % len(scopes)]
        inputs = random_case(rng, scope)
        generated.append({"id": f"P{n:04d}", "scope": scope, "source": "property", "inputs": inputs,
                          "expected": ref.compute(scope, inputs), "rationale": f"seed={seed}"})
    failures = 0
    for case in generated:
        actual, error = run_catala(case["scope"], case["inputs"], calendar)
        problems = [error[:300]] if error else compare_outputs(case["expected"], actual)
        if problems:
            failures += 1
            print(f"FAIL catala {case['id']} {case['scope']} {json.dumps(case['inputs'])}: {'; '.join(problems)}")
    print(f"property/catala: {count - failures}/{count} random cases matched the Python reference (seed {seed})")
    if not with_lawc:
        return 1 if failures else 0
    # lawc on the same cases: generated tests in a private profile snapshot.
    rendered = render_suites({"cases": generated})
    with tempfile.TemporaryDirectory(prefix="vred-ts-property-") as tmp:
        snapshot = Path(tmp) / "snapshot"
        if subprocess.run([python, str(ROOT / "verify/ci/tools/work_profile.py"), "--build-only", "--output", str(snapshot)],
                          cwd=ROOT, capture_output=True).returncode:
            print("failed to build a private profile snapshot", file=sys.stderr)
            return 1
        sys.path[:0] = [str(ROOT / "corpus"), str(ROOT / "corpus/lib"), str(ROOT / "engines/lawref")]
        os.environ["LAW_WORK_PROFILE_STATE"] = str(snapshot / "state.json")
        from lawtests.run import world_json, context_json, LAWCLI  # noqa: E402
        # The §85 calendar dataset is looked up upward from the test file along artifact:corpus/clir/…
        dataset = ROOT / cases["calendar_dataset"]
        (Path(tmp) / "corpus/clir").mkdir(parents=True)
        shutil.copyfile(dataset, Path(tmp) / "corpus/clir" / dataset.name)
        lawc_failures = 0
        for name, text in rendered.items():
            path = Path(tmp) / name
            path.write_text(text, encoding="utf-8")
            world = ["kz.corpus.vred_ts"] + (["kz.corpus.clir.official_calendar"] if "sroki" in name else [])
            program = Path(tmp) / f"{name}.world.json"
            program.write_text(world_json(tuple(world)), encoding="utf-8")
            listing = Path(tmp) / f"{name}.list.json"
            listing.write_text(json.dumps([str(path)]), encoding="utf-8")
            imports = Path(tmp) / f"{name}.imports.json"
            imports.write_text(context_json(tuple(world)), encoding="utf-8")
            result = subprocess.run([str(LAWCLI), "test", str(listing), "--lawtest-list", "--program", str(program),
                                     "--imports", str(imports), "--json"], capture_output=True, text=True)
            try:
                report = json.loads(result.stdout)
                report["tests"]
            except (ValueError, KeyError):
                print(f"lawc test did not produce a suite report: {(result.stdout + result.stderr)[-1200:]}", file=sys.stderr)
                return 1
            for item in report["tests"]:
                if not item["passed"]:
                    lawc_failures += 1
                    print(f"FAIL lawc {item['title']}: {'; '.join(item['failures'])}")
        print(f"property/lawc: {count - lawc_failures}/{count} random cases matched the Python reference (seed {seed})")
    return 1 if (failures or lawc_failures) else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--emit", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--catala", action="store_true")
    parser.add_argument("--engines", action="store_true")
    parser.add_argument("--property", type=int, metavar="N")
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--no-lawc", action="store_true", help="in --property, only Catala against the reference")
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--verbose", action="store_true")
    parser.add_argument("--python", default=os.environ.get("LAW_WORK_PYTHON") or (
        str(ROOT / ".venv-work-profile/bin/python") if (ROOT / ".venv-work-profile/bin/python").exists() else sys.executable))
    args = parser.parse_args()
    rc = 0
    if args.emit:
        rc |= emit(check=False)
    if args.check or args.all:
        rc |= emit(check=True)
    if args.catala or args.all:
        rc |= check_catala(args.verbose)
    if args.engines or args.all:
        rc |= run_engines(args.python)
    if args.property:
        rc |= run_property(args.property, args.seed, args.python, not args.no_lawc)
    if not any((args.emit, args.check, args.catala, args.engines, args.property, args.all)):
        parser.print_help()
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
