def run_engines(python: str) -> int:
    if emit(check=True):
        return 1
    with tempfile.TemporaryDirectory(prefix="vred-ts-parity-") as tmp:
        snapshot = Path(tmp) / "snapshot"
        build = subprocess.run([python, str(ROOT / "verify/ci/tools/work_profile.py"), "--build-only", "--output", str(snapshot)],
                               cwd=ROOT)
        if build.returncode:
            return build.returncode
        env = dict(os.environ, LAW_WORK_PROFILE_STATE=str(snapshot / "state.json"), PYTHONUNBUFFERED="1")
        gate = subprocess.run([python, str(ROOT / "verify/ci/gates/compiler/check_lawtest_suites.py"), "--only", FAMILY],
                              cwd=ROOT, env=env)
        return gate.returncode


